#!/usr/bin/env python3
"""Download DJI official LUTs listed in tools/dji_lut_sources.json.

The script is intentionally inside the project and writes only to:
  temp/dji_lut_download/   (download cache)
  luts/<Device>/<Category>/ (final LUT library)
  luts/manifest.json        (generated library metadata)
  luts/SOURCES.md           (source/asset report)
"""
from __future__ import annotations

import hashlib
import io
import json
import re
import shutil
import sys
import time
import urllib.parse
import urllib.request
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from dlog_grader.lut import CubeLUT  # noqa: E402

LUT_DIR = PROJECT_ROOT / "luts"
CACHE_DIR = PROJECT_ROOT / "temp" / "dji_lut_download"
SOURCE_FILE = PROJECT_ROOT / "tools" / "dji_lut_sources.json"
DEFAULT_LUT_REL = "DJI Air 3S/Normalization/DJI Air 3s DJI D-Log M to Rec.709.cube"
DEFAULT_LUT = LUT_DIR / DEFAULT_LUT_REL

_UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) DJI-LUT-Collector/2.0"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def safe_component(name: str) -> str:
    name = urllib.parse.unquote(name)
    name = re.sub(r'[<>:"/\|?*]', "_", name)
    name = re.sub(r"\s+", " ", name).strip(" .")
    return name or "DJI Other"


def download(url: str, dest: Path) -> bytes:
    if dest.exists() and dest.stat().st_size > 0:
        return dest.read_bytes()
    dest.parent.mkdir(parents=True, exist_ok=True)
    safe_url = urllib.parse.quote(url, safe=":/?&=%#[]@!$'()*+,;~")
    req = urllib.request.Request(safe_url, headers={"User-Agent": _UA})
    last_error: Exception | None = None
    for attempt in range(1, 4):
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                data = resp.read()
            if not data:
                raise RuntimeError("服务器返回空文件")
            tmp = dest.with_suffix(dest.suffix + ".part")
            tmp.write_bytes(data)
            tmp.replace(dest)
            return data
        except Exception as exc:
            last_error = exc
            time.sleep(attempt * 2)
    raise RuntimeError(f"下载失败：{url}\n{last_error}")


def validate_cube(path: Path) -> bool:
    try:
        CubeLUT.from_file(path)
        return True
    except Exception as exc:
        print(f"  [无效] {path.name}: {exc}")
        return False


def unique_destination(folder: Path, filename: str, data_hash: str) -> Path | None:
    folder.mkdir(parents=True, exist_ok=True)
    candidate = folder / safe_component(filename)
    if not candidate.suffix:
        candidate = candidate.with_suffix(".cube")
    index = 2
    while candidate.exists():
        if sha256_file(candidate) == data_hash:
            return candidate
        candidate = folder / f"{candidate.stem}_{index}.cube"
        index += 1
    return candidate


def build_sources_md(records: list[dict]) -> str:
    lines = [
        "# DJI Official LUT Sources",
        "",
        "Generated by `tools/download_dji_luts.py`.",
        "",
        "The LUT files are downloaded from DJI official CDN links referenced by the",
        "DJI Download Center. DJI and related marks belong to DJI. Verify DJI terms",
        "before redistributing a commercial package.",
        "",
        "| Device | Category | LUT / pack | Source URL |",
        "|---|---|---|---|",
    ]
    for r in records:
        name = str(r.get("name", "")).replace("|", r"\|")
        url = str(r.get("url", ""))
        lines.append(f"| {r.get('device','')} | {r.get('category','')} | {name} | {url} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    source_data = json.loads(SOURCE_FILE.read_text(encoding="utf-8"))
    sources = source_data.get("entries", [])
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    records: list[dict] = []
    errors: list[str] = []
    downloaded_cubes = 0

    print(f"开始处理 {len(sources)} 个 DJI 官方 LUT 资源 ...")
    for index, src in enumerate(sources, 1):
        name = str(src.get("name") or src.get("slug") or f"source_{index}")
        url = str(src.get("url") or "")
        device = safe_component(str(src.get("device") or "DJI Other"))
        category = safe_component(str(src.get("category") or "Normalization"))
        fmt = "zip" if url.lower().endswith(".zip") else "cube"
        print(f"\n[{index}/{len(sources)}] {device} / {name}")
        print(f"  {url}")
        try:
            suffix = ".zip" if fmt == "zip" else ".cube"
            cache_file = CACHE_DIR / f"{index:02d}_{safe_component(name)[:100]}{suffix}"
            data = download(url, cache_file)
            zip_hash = sha256_bytes(data)
            target_dir = LUT_DIR / device / category
            if fmt == "cube":
                tmp_cube = CACHE_DIR / f"validate_{index:02d}.cube"
                tmp_cube.write_bytes(data)
                if not validate_cube(tmp_cube):
                    errors.append(f"{name}: invalid cube")
                    continue
                dest = unique_destination(target_dir, cache_file.name.split("_", 1)[1], zip_hash)
                if dest is None:
                    continue
                if not dest.exists():
                    dest.write_bytes(data)
                downloaded_cubes += 1
                records.append({
                    "file": dest.relative_to(LUT_DIR).as_posix(),
                    "device": device,
                    "profile": str(src.get("profile") or ""),
                    "category": category,
                    "name": name,
                    "description": f"{device} · {name}（DJI 官方下载）",
                    "sha256": sha256_file(dest),
                    "source_url": url,
                    "source_page": str(src.get("source_page") or ""),
                    "version": str(src.get("version") or ""),
                    "release_at": str(src.get("release_at") or ""),
                })
                print(f"  -> {dest.relative_to(PROJECT_ROOT)}")
            else:
                with zipfile.ZipFile(io.BytesIO(data)) as zf:
                    cube_members = [n for n in zf.namelist() if n.lower().endswith(".cube") and not n.endswith("/")]
                    if not cube_members:
                        errors.append(f"{name}: zip contains no .cube files")
                        print("  [跳过] zip 内没有 .cube")
                        continue
                    print(f"  zip 内发现 {len(cube_members)} 个 .cube")
                    for member in cube_members:
                        member_data = zf.read(member)
                        tmp_cube = CACHE_DIR / f"validate_{index:02d}_{safe_component(Path(member).name)}"
                        tmp_cube.write_bytes(member_data)
                        if not validate_cube(tmp_cube):
                            continue
                        dest = unique_destination(target_dir, Path(member).name, sha256_bytes(member_data))
                        if dest is None:
                            continue
                        if not dest.exists():
                            dest.write_bytes(member_data)
                        downloaded_cubes += 1
                        records.append({
                            "file": dest.relative_to(LUT_DIR).as_posix(),
                            "device": device,
                            "profile": str(src.get("profile") or ""),
                            "category": category,
                            "name": Path(member).stem,
                            "description": f"{device} · {name} · {Path(member).name}（DJI 官方下载）",
                            "sha256": sha256_file(dest),
                            "source_url": url,
                            "source_page": str(src.get("source_page") or ""),
                            "version": str(src.get("version") or ""),
                            "release_at": str(src.get("release_at") or ""),
                        })
                        print(f"  -> {dest.relative_to(PROJECT_ROOT)}")
        except Exception as exc:
            errors.append(f"{name}: {exc}")
            print(f"  [失败] {exc}")

    # The official Air 3S LUT is the default, but never duplicate the old
    # user-provided root-level copy.
    entries = []
    seen_files = set()
    for record in records:
        if record["file"] not in seen_files:
            entries.append(record)
            seen_files.add(record["file"])

    manifest = {
        "version": 1,
        "default": DEFAULT_LUT_REL,
        "generated_at": time.strftime("%Y-%m-%d"),
        "source_catalog": source_data.get("source_catalog", ""),
        "count": len(entries),
        "entries": entries,
    }
    LUT_DIR.mkdir(parents=True, exist_ok=True)
    (LUT_DIR / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (LUT_DIR / "SOURCES.md").write_text(build_sources_md(sources), encoding="utf-8")
    (LUT_DIR / "DOWNLOAD_REPORT.json").write_text(
        json.dumps({"downloaded_cubes": downloaded_cubes, "errors": errors, "sources": sources},
                   ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"\n完成：{downloaded_cubes} 个 LUT 文件，{len(errors)} 个错误")
    if errors:
        for err in errors:
            print(" -", err)
    print(f"清单：{LUT_DIR / 'manifest.json'}")
    return 0 if downloaded_cubes else 1


if __name__ == "__main__":
    raise SystemExit(main())
